//! Clipboard watching: announce when new text is copied, without reading
//! clipboard contents until the user plays them (port of
//! `ClipboardMonitor.swift`'s logic).
//!
//! [`watch`] starts one background thread that sends [`ClipboardEvent::Changed`]
//! for new text that is not marked secret. [`read_text`] reads the current
//! text on demand. Callers ignore texts shorter than 2 characters.

use std::error::Error;
use std::fmt;
use std::sync::mpsc;

#[cfg(target_os = "macos")]
mod macos;
#[cfg(target_os = "macos")]
use self::macos as backend;

#[cfg(target_os = "windows")]
mod windows;
#[cfg(target_os = "windows")]
use self::windows as backend;

#[cfg(target_os = "linux")]
mod linux;
#[cfg(target_os = "linux")]
use self::linux as backend;

#[cfg(not(any(target_os = "macos", target_os = "windows", target_os = "linux")))]
compile_error!("clipboard watching is only implemented for macOS, Windows and Linux");

/// Events from the clipboard watcher.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ClipboardEvent {
    /// New text was copied (contents not read). `source_app` is the frontmost
    /// app's name when the platform provides it.
    Changed { source_app: Option<String> },
    /// The watcher failed and has stopped.
    Error(String),
}

/// Errors from watching or reading the clipboard. The message is always
/// user-facing: it names the step and keeps the OS error text.
#[derive(Debug)]
pub enum ClipboardError {
    /// Watching isn't available on this desktop (message used verbatim).
    Unsupported(String),
    /// An OS call failed.
    Backend(String),
}

impl fmt::Display for ClipboardError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ClipboardError::Unsupported(message) | ClipboardError::Backend(message) => {
                write!(f, "{message}")
            }
        }
    }
}

impl Error for ClipboardError {}

/// Handle for the watcher background thread; dropping it stops the thread.
pub struct Watcher {
    inner: backend::Watcher,
}

impl Watcher {
    /// Pause (`false`) or resume (`true`) change reports. Copies made while
    /// paused are not reported later.
    pub fn set_enabled(&self, enabled: bool) {
        self.inner.set_enabled(enabled);
    }
}

/// Start watching the clipboard on a background thread, sending [`Changed`]
/// events to `events`. The watcher never reads clipboard contents itself.
///
/// [`Changed`]: ClipboardEvent::Changed
pub fn watch(events: mpsc::Sender<ClipboardEvent>) -> Result<Watcher, ClipboardError> {
    backend::watch(events).map(|inner| Watcher { inner })
}

/// Read the current clipboard text (`None` when it holds no text). Called only
/// when the user plays, never by the watcher.
pub fn read_text() -> Result<Option<String>, ClipboardError> {
    backend::read_text()
}

/// Minimum text length callers accept (Swift's `minimumReadyLength`).
pub const MIN_TEXT_LEN: usize = 2;

/// Pasteboard types marking a copy as secret on macOS (password managers,
/// transient/autogenerated content): never announced.
#[cfg(any(test, target_os = "macos"))]
pub(crate) const MACOS_SECRET_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

/// Pasteboard type a macOS copy must offer to count as text.
#[cfg(any(test, target_os = "macos"))]
pub(crate) const MACOS_TEXT_TYPE: &str = "public.utf8-plain-text";

/// Should a macOS change offering these pasteboard `types` produce an event?
/// Port of `ClipboardMonitor.poll`'s filter: skip secret markers, require text.
#[cfg(any(test, target_os = "macos"))]
pub(crate) fn macos_should_notify(types: &[&str]) -> bool {
    if types.iter().any(|t| MACOS_SECRET_TYPES.contains(t)) {
        return false;
    }
    types.contains(&MACOS_TEXT_TYPE)
}

/// Custom clipboard format names marking a copy as secret on Windows
/// (password managers set these).
#[cfg(any(test, target_os = "windows"))]
pub(crate) const WINDOWS_SECRET_FORMATS: &[&str] = &[
    "ExcludeClipboardContentFromMonitorProcessing",
    "Clipboard Viewer Ignore",
];

/// Format whose presence with value 0 opts a copy out of clipboard history.
#[cfg(any(test, target_os = "windows"))]
pub(crate) const WINDOWS_HISTORY_OPT_OUT: &str = "CanIncludeInClipboardHistory";

/// Should a Windows clipboard update produce an event? `present` holds the
/// custom format names currently available; `history_value` is the DWORD stored
/// under [`WINDOWS_HISTORY_OPT_OUT`] when that format is present (`None` when
/// it couldn't be read, treated as opted out).
#[cfg(any(test, target_os = "windows"))]
pub(crate) fn windows_should_notify(
    has_text: bool,
    present: &[&str],
    history_value: Option<u32>,
) -> bool {
    if !has_text {
        return false;
    }
    if present
        .iter()
        .any(|name| WINDOWS_SECRET_FORMATS.contains(name))
    {
        return false;
    }
    if present.contains(&WINDOWS_HISTORY_OPT_OUT) && history_value.unwrap_or(0) == 0 {
        return false;
    }
    true
}

/// X11 target marking a copy as a password (`x-kde-passwordManagerHint`).
#[cfg(any(test, target_os = "linux"))]
pub(crate) const LINUX_PASSWORD_HINT: &str = "x-kde-passwordManagerHint";

/// Hint value meaning the copy is secret.
#[cfg(any(test, target_os = "linux"))]
pub(crate) const LINUX_PASSWORD_HINT_SECRET: &str = "secret";

/// Should an X11 selection-owner change produce an event? `targets` are the
/// target names the new owner offers; `hint_value` is the password-hint value
/// when the owner offers the hint.
#[cfg(any(test, target_os = "linux"))]
pub(crate) fn linux_should_notify(targets: &[&str], hint_value: Option<&str>) -> bool {
    if targets.contains(&LINUX_PASSWORD_HINT) && hint_value == Some(LINUX_PASSWORD_HINT_SECRET) {
        return false;
    }
    true
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn macos_text_is_announced() {
        assert!(macos_should_notify(&["public.utf8-plain-text"]));
        assert!(macos_should_notify(&[
            "NSStringPboardType",
            "public.utf8-plain-text",
            "public.tiff",
        ]));
    }

    #[test]
    fn macos_non_text_is_ignored() {
        assert!(!macos_should_notify(&[]));
        assert!(!macos_should_notify(&["public.tiff"]));
    }

    #[test]
    fn macos_secret_markers_are_skipped() {
        for secret in MACOS_SECRET_TYPES {
            assert!(
                !macos_should_notify(&["public.utf8-plain-text", secret]),
                "{secret} must suppress the event"
            );
        }
    }

    #[test]
    fn windows_text_is_announced() {
        assert!(windows_should_notify(true, &[], None));
    }

    #[test]
    fn windows_non_text_is_ignored() {
        assert!(!windows_should_notify(false, &[], None));
    }

    #[test]
    fn windows_secret_markers_are_skipped() {
        for secret in WINDOWS_SECRET_FORMATS {
            assert!(
                !windows_should_notify(true, &[*secret], None),
                "{secret} must suppress the event"
            );
        }
    }

    #[test]
    fn windows_history_opt_out_is_skipped() {
        assert!(!windows_should_notify(
            true,
            &[WINDOWS_HISTORY_OPT_OUT],
            Some(0)
        ));
        // Unreadable value: conservative, treated as opted out.
        assert!(!windows_should_notify(
            true,
            &[WINDOWS_HISTORY_OPT_OUT],
            None
        ));
        // Present with a nonzero value: a normal copy.
        assert!(windows_should_notify(
            true,
            &[WINDOWS_HISTORY_OPT_OUT],
            Some(1)
        ));
        // Absent: a normal copy.
        assert!(windows_should_notify(true, &[], Some(0)));
    }

    #[test]
    fn linux_plain_copy_is_announced() {
        assert!(linux_should_notify(&["TARGETS", "UTF8_STRING"], None));
        assert!(linux_should_notify(&[], None));
    }

    #[test]
    fn linux_password_hint_is_skipped_only_when_secret() {
        assert!(!linux_should_notify(
            &["TARGETS", LINUX_PASSWORD_HINT],
            Some("secret")
        ));
        assert!(linux_should_notify(
            &["TARGETS", LINUX_PASSWORD_HINT],
            Some("not-secret")
        ));
        assert!(linux_should_notify(&["TARGETS", LINUX_PASSWORD_HINT], None));
    }
}
