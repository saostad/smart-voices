import Testing
@testable import SmartVoicesCore

final class FakePasteboard: PasteboardSource {
    var changeCount = 0
    var types: [String] = ["public.utf8-plain-text"]
    var text: String? = "hello"
    var stringCalls = 0

    func string() -> String? {
        stringCalls += 1
        return text
    }
}

@Suite @MainActor
struct ClipboardMonitorTests {
    @Test func changeDetected() {
        let fake = FakePasteboard()
        let monitor = ClipboardMonitor(source: fake)
        #expect(monitor.hasUnreadContent == false)
        fake.changeCount = 1
        monitor.poll()
        #expect(monitor.hasUnreadContent == true)
        #expect(fake.stringCalls == 0)
    }

    @Test func concealedIgnored() {
        for concealed in [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
        ] {
            let fake = FakePasteboard()
            let monitor = ClipboardMonitor(source: fake)
            fake.types = ["public.utf8-plain-text", concealed]
            fake.changeCount = 1
            monitor.poll()
            #expect(monitor.hasUnreadContent == false, "\(concealed)")
        }
    }

    @Test func nonTextIgnored() {
        let fake = FakePasteboard()
        let monitor = ClipboardMonitor(source: fake)
        fake.types = ["public.png"]
        fake.changeCount = 1
        monitor.poll()
        #expect(monitor.hasUnreadContent == false)
    }

    @Test func disabledIgnores() {
        let fake = FakePasteboard()
        let monitor = ClipboardMonitor(source: fake)
        monitor.isEnabled = false
        fake.changeCount = 1
        monitor.poll()
        #expect(monitor.hasUnreadContent == false)
        monitor.isEnabled = true
        monitor.poll()
        #expect(monitor.hasUnreadContent == false)
        fake.changeCount = 2
        monitor.poll()
        #expect(monitor.hasUnreadContent == true)
        #expect(fake.stringCalls == 0)
    }

    @Test func disablingClearsPendingCopy() {
        let fake = FakePasteboard()
        let monitor = ClipboardMonitor(source: fake)
        fake.changeCount = 1
        monitor.poll()
        #expect(monitor.hasUnreadContent == true)

        monitor.isEnabled = false
        #expect(monitor.hasUnreadContent == false)
        #expect(
            !AutoReadPolicy.shouldRead(
                autoReadEnabled: true, hasUnreadContent: monitor.hasUnreadContent, isExporting: false))
        #expect(fake.stringCalls == 0)
    }

    @Test func unchangedEnabledStateDoesNotLoseNewCopy() {
        let fake = FakePasteboard()
        let monitor = ClipboardMonitor(source: fake)
        fake.changeCount = 1
        monitor.isEnabled = true
        monitor.poll()
        #expect(monitor.hasUnreadContent == true)
    }

    @Test func manualReadStillWorksWhenDisabled() {
        let fake = FakePasteboard()
        fake.text = "Read this copy manually."
        let monitor = ClipboardMonitor(source: fake)
        monitor.isEnabled = false
        fake.changeCount = 1
        monitor.poll()
        #expect(monitor.hasUnreadContent == false)
        #expect(fake.stringCalls == 0)
        #expect(monitor.readText() == .text("Read this copy manually."))
        #expect(fake.stringCalls == 1)
    }

    @Test func readClears() {
        let fake = FakePasteboard()
        fake.text = "clip text"
        let monitor = ClipboardMonitor(source: fake)
        fake.changeCount = 1
        monitor.poll()
        #expect(monitor.hasUnreadContent == true)
        #expect(monitor.readText() == .text("clip text"))
        #expect(monitor.hasUnreadContent == false)
    }

    @Test func ignoredSourceApp() {
        let fake = FakePasteboard()
        let monitor = ClipboardMonitor(source: fake, frontmostAppProvider: { "com.1password.1password" })
        monitor.ignoredAppBundleIDs = ["com.1password.1password"]
        fake.changeCount = 1
        monitor.poll()
        #expect(monitor.hasUnreadContent == false)
        monitor.frontmostAppProvider = { "com.example.notes" }
        fake.changeCount = 2
        monitor.poll()
        #expect(monitor.hasUnreadContent == true)
    }

    @Test func readTextResults() {
        let fake = FakePasteboard()
        let monitor = ClipboardMonitor(source: fake)
        monitor.minimumReadyLength = 5
        fake.text = nil
        #expect(monitor.readText() == .empty)
        fake.text = "hi"
        #expect(monitor.readText() == .tooShort(2))
        fake.text = "hello there"
        #expect(monitor.readText() == .text("hello there"))
    }
}
