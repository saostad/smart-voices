import AppKit
import Foundation
import Observation

/// Pasteboard access for clipboard monitoring.
public protocol PasteboardSource: AnyObject {
    var changeCount: Int { get }
    var types: [String] { get }
    func string() -> String?
}

/// System pasteboard source.
public final class SystemPasteboard: PasteboardSource {
    public init() {}

    public var changeCount: Int { NSPasteboard.general.changeCount }
    public var types: [String] { NSPasteboard.general.types?.map(\.rawValue) ?? [] }
    public func string() -> String? { NSPasteboard.general.string(forType: .string) }
}

/// Watches the clipboard for new text.
@MainActor @Observable
public final class ClipboardMonitor {
    public var hasUnreadContent = false
    public var isEnabled = true {
        didSet {
            if isEnabled {
                lastChangeCount = source.changeCount
                startTimer()
            } else {
                stopTimer()
            }
        }
    }

    private let source: any PasteboardSource
    private var lastChangeCount: Int
    private var timer: Timer?

    public init(source: (any PasteboardSource)? = nil) {
        let resolved = source ?? SystemPasteboard()
        self.source = resolved
        self.lastChangeCount = resolved.changeCount
        startTimer()
    }

    isolated deinit {
        timer?.invalidate()
    }

    /// Read the clipboard string and clear the unread flag.
    public func readText() -> String? {
        let text = source.string()
        hasUnreadContent = false
        return text
    }

    func poll() {
        guard isEnabled else { return }
        let current = source.changeCount
        guard current != lastChangeCount else { return }
        lastChangeCount = current
        let types = source.types
        if types.contains("org.nspasteboard.ConcealedType")
            || types.contains("org.nspasteboard.TransientType")
            || types.contains("org.nspasteboard.AutoGeneratedType")
        {
            return
        }
        if !types.contains("public.utf8-plain-text") {
            return
        }
        hasUnreadContent = true
    }

    private func startTimer() {
        stopTimer()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            guard let self else { return }
            MainActor.assumeIsolated {
                self.poll()
            }
        }
    }

    private func stopTimer() {
        timer?.invalidate()
        timer = nil
    }
}
